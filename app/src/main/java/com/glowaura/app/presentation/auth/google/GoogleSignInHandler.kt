package com.glowaura.app.presentation.auth.google

import android.content.Context
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import androidx.credentials.exceptions.NoCredentialException
import com.glowaura.app.R
import com.glowaura.app.domain.model.AuthError
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import kotlinx.coroutines.CancellationException

/** Result of asking the user to pick a Google account. */
sealed interface GoogleIdTokenResult {
    /** Raw OIDC id token, ready to be exchanged for a Firebase credential. */
    data class Success(val idToken: String) : GoogleIdTokenResult

    /** The user dismissed the account chooser. Not an error, so nothing is surfaced. */
    data object Cancelled : GoogleIdTokenResult

    data class Failure(val error: AuthError) : GoogleIdTokenResult
}

/**
 * Wraps Credential Manager's Google ID flow and returns a raw OIDC id token.
 *
 * Returning the token rather than signing in here keeps the Firebase exchange inside
 * the repository, where dispatcher switching and error mapping already live.
 *
 * Must be invoked from the main thread: Credential Manager drives system UI.
 */
class GoogleIdTokenProvider(private val context: Context) {

    private val credentialManager by lazy {
        androidx.credentials.CredentialManager.create(context)
    }

    /**
     * OAuth client id of type "Web".
     *
     * Read from `res/values/strings.xml` (`google_web_client_id`) instead of the
     * `default_web_client_id` generated by the google-services plugin, so this class
     * compiles whether or not that plugin has been applied.
     */
    private val serverClientId: String?
        get() = runCatching {
            context.getString(R.string.google_web_client_id).trim().takeIf(String::isNotEmpty)
        }.getOrNull()

    suspend fun requestIdToken(): GoogleIdTokenResult {
        val clientId = serverClientId
            ?: return GoogleIdTokenResult.Failure(AuthError.FirebaseNotConfigured)

        return try {
            val googleIdOption = GetGoogleIdOption.Builder()
                // false shows the full account chooser instead of silently reusing a
                // previously authorised account.
                .setFilterByAuthorizedAccounts(false)
                .setServerClientId(clientId)
                .setAutoSelectEnabled(false)
                .build()

            val request = GetCredentialRequest.Builder()
                .addCredentialOption(googleIdOption)
                .build()

            val response = credentialManager.getCredential(context, request)

            val credential = GoogleIdTokenCredential.createFrom(response.credential.data)
            val idToken = credential.idToken

            if (idToken.isNullOrBlank()) {
                GoogleIdTokenResult.Failure(AuthError.InvalidCredential)
            } else {
                GoogleIdTokenResult.Success(idToken)
            }
        } catch (cancellation: GetCredentialCancellationException) {
            GoogleIdTokenResult.Cancelled
        } catch (noCredential: NoCredentialException) {
            GoogleIdTokenResult.Failure(AuthError.Unknown("No Google account was selected."))
        } catch (exception: GetCredentialException) {
            GoogleIdTokenResult.Failure(
                AuthError.Unknown(exception.message ?: "Google sign-in is unavailable on this device.")
            )
        } catch (cancellation: CancellationException) {
            throw cancellation
        } catch (throwable: Throwable) {
            GoogleIdTokenResult.Failure(AuthError.Unknown(throwable.message.orEmpty()))
        }
    }
}